#[derive(Debug, EnumCount)]
pub enum DesktopClientMfaEvent {
    Success {
        device: Device<Id>,
        location: WireguardNetwork<Id>,
        /// The complete challenge-and-response record and the governing flow's title.
        attribution: MfaAttribution,
        /// Name of the device used to approve the login when the mobile approve
        /// MFA method is used. `None` for all other methods.
        mobile_auth_device_name: Option<String>,
    },
    Failed {
        device: Device<Id>,
        location: WireguardNetwork<Id>,
        method: ClientMFAMethod,
        message: String,
    },
    /// An MFA login used too many tries for a step.
    Aborted {
        device: Device<Id>,
        location: WireguardNetwork<Id>,
        /// Saved step details and the flow name.
        attribution: MfaAttribution,
    },
    Disconnected {
        device: Device<Id>,
        location: WireguardNetwork<Id>,
        is_mfa_session: bool,
    },
    /// An authorized VPN session was replaced by a new authorization.
    SessionSuperseded {
        device: Device<Id>,
        location: WireguardNetwork<Id>,
        is_mfa_session: bool,
    },
    /// An in-progress MFA login was replaced by a new login attempt for the same device and
    /// location. Distinct from [`Self::SessionSuperseded`]: nothing was authorized yet, so no
    /// VPN session existed to supersede.
    MfaLoginSuperseded {
        device: Device<Id>,
        location: WireguardNetwork<Id>,
    },
    /// The device met the posture policies of the location.
    PostureCheckPassed {
        device: Device<Id>,
        location: WireguardNetwork<Id>,
        facts: Option<crate::posture::PostureFacts>,
    },
    /// The device did not meet the posture policies of the location (at connect time, or when
    /// the policies changed while it was connected).
    PostureCheckFailed {
        device: Device<Id>,
        location: WireguardNetwork<Id>,
        facts: Option<crate::posture::PostureFacts>,
        failed_checks: Vec<String>,
    },
}

