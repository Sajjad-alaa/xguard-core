/// Shared context that needs to be added to every API event
///
/// Mainly meant to be stored in the activity log.
/// By design this is a duplicate of a similar struct in the `event_logger` module.
/// This is done in order to avoid circular imports once we split the project into multiple crates.
#[derive(Debug, Clone, PartialEq)]
pub struct ApiRequestContext {
    pub timestamp: NaiveDateTime,
    /// `None` for events about a user that doesn't have an account yet, e.g. an
    /// OpenID login blocked before the corresponding account could be created.
    pub user_id: Option<Id>,
    pub username: String,
    pub ip: Option<IpAddr>,
    pub device: String,
}

impl ApiRequestContext {
    #[must_use]
    pub fn new(
        user_id: impl Into<Option<Id>>,
        username: String,
        ip: impl Into<Option<IpAddr>>,
        device: String,
    ) -> Self {
        let timestamp = Utc::now().naive_utc();
        Self {
            timestamp,
            user_id: user_id.into(),
            username,
            ip: ip.into(),
            device,
        }
    }
}

